"""Writes docs/FINDINGS.md from the committed outputs. No number in it is typed by hand.

Inputs: data/out/weekly.csv, data/out/results.json, data/out/controls.json, data/out/lags.csv,
data/out/fc_receivers.csv. Run after analysis/controls.py (make analyze does).
"""
import json

import pandas as pd

LABEL = {
    "fc_signed_tx": "function-call-signed transactions",
    "fc_share": "function-call share",
    "daa": "daily active accounts",
    "tx_count": "transaction count",
    "price": "NEAR price",
}


def pct(x, d=1):
    return "n/a" if x is None or pd.isna(x) else f"{x * 100:.{d}f}%"


def main():
    w = pd.read_csv("data/out/weekly.csv")
    res = json.load(open("data/out/results.json"))
    ctl = json.load(open("data/out/controls.json"))
    lags = pd.read_csv("data/out/lags.csv")
    rec = pd.read_csv("data/out/fc_receivers.csv")

    w = w[w.txs_classified > 0].copy()
    w["year"] = w.monday.str[:4]
    n = w.txs_classified
    w["delegated"] = (w.n_delegated_inner_fc + w.n_delegated_inner_full) / n
    w["implicit"] = w.n_implicit_full / n
    w["full"] = w.n_full_access / n
    by = w.groupby("year").agg(
        weeks=("week", "count"), txs=("txs_classified", "sum"),
        fc=("fc_only_share", "mean"), fc_incl=("fc_share", "mean"),
        delegated=("delegated", "mean"), implicit=("implicit", "mean"), full=("full", "mean"),
    )

    L = ["# Findings", ""]
    L.append(f"Generated by `analysis/findings.py` from the committed outputs ({len(w)} sampled weeks, {w.monday.min()} to {w.monday.max()}). Rerun with `make analyze`.")
    L.append("")

    # 1. The verdict
    g = res["oos_gain_vs_ar2"]
    lag = res["best_in_sample_lag"]
    L.append("## 1. The registered test")
    L.append("")
    L.append(f"**{res['verdict']}.** Over {res['oos_weeks_scored']} out-of-sample weeks, each signal was added to an AR(2) forecast of weekly USDC volume at the lag chosen on in-sample weeks only. Gain is 1 minus the model's squared error over the baseline's: positive means smaller errors.")
    L.append("")
    L.append("| Signal | In-sample lag (weeks) | In-sample gain | In-sample Spearman | Out-of-sample gain |")
    L.append("|---|---|---|---|---|")
    for k in ["fc_signed_tx", "fc_share", "daa", "tx_count", "price"]:
        row = lags[(lags.candidate == k) & (lags.lag == lag[k])]
        ig = row.in_gain.iloc[0] if len(row) else None
        sp = row.in_spearman.iloc[0] if len(row) and "in_spearman" in row else None
        L.append(f"| {LABEL[k]} | {lag[k]} | {pct(ig)} | {'n/a' if sp is None or pd.isna(sp) else f'{sp:.2f}'} | {pct(g[k])} |")
    L.append("")
    fc_in = lags[(lags.candidate == "fc_signed_tx") & (lags.lag == lag["fc_signed_tx"])]
    better = [LABEL[k] for k, v in g.items() if v is not None and v > 0]
    L.append(f"What happened: in-sample, function-call-signed activity at a {lag['fc_signed_tx']}-week lag lowered the error by {pct(fc_in.in_gain.iloc[0])}, but with a negative rank correlation ({fc_in.in_spearman.iloc[0]:.2f}), so the fit was leaning on a relationship that ran the wrong way for a leading indicator. Out of sample the gain turned to {pct(g['fc_signed_tx'])}. Signals that lowered the out-of-sample error at all: {', '.join(better) if better else 'none'}. That is what a lag chosen on {int(fc_in.n.iloc[0])} noisy weeks looks like when it does not carry over.")
    L.append("")
    cd, cp = res["comparisons"]["daa"], res["comparisons"]["price"]
    L.append(f"Against DAA the mean squared-error difference is {cd['mean_sq_error_difference']:.6f} (95% interval {cd['ci95'][0]:.6f} to {cd['ci95'][1]:.6f}); against price {cp['mean_sq_error_difference']:.6f} ({cp['ci95'][0]:.6f} to {cp['ci95'][1]:.6f}). The pass rule needs both intervals below zero. Timing placebo: the real gain beats {pct(ctl['placebo']['share_of_placebos_beaten'], 0)} of {ctl['placebo']['reps']} shifted series (the bar is 95%).")
    L.append("")
    L.append("Files: `data/out/results.json`, `data/out/lags.csv`, `data/out/oos_errors.csv`, `data/out/placebo.csv`. Method: `docs/METHOD.md` (hash on chain).")
    L.append("")

    # 2. Surprising finding: the key mix moved from scoped keys to relayed meta transactions
    L.append("## 2. Surprising finding: the signer moved, from app-held keys to relayers")
    L.append("")
    first, last = by.index.min(), by.index.max()
    L.append(f"The share of sampled transactions signed directly by a function-call key averaged {pct(by.loc[first, 'fc'])} in {first} and {pct(by.loc[last, 'fc'])} in {last}, with a low of {pct(by.fc.min())} in {by.fc.idxmin()}. Meaning: the classic pattern, where an app holds a scoped key for its user and signs on its own, faded. NEP-366 meta transactions, where a relayer pays gas and the user's key signs the inner action, rose from {pct(by.loc[first, 'delegated'])} to a peak yearly average of {pct(by.delegated.max())} in {by.delegated.idxmax()}.")
    L.append("")
    L.append("| Year | Weeks | Transactions classified | Function-call key | Meta transaction (relayed) | Implicit account | Full-access key | Function-call incl. relayed inner FC |")
    L.append("|---|---|---|---|---|---|---|---|")
    for y, r in by.iterrows():
        L.append(f"| {y} | {int(r.weeks)} | {int(r.txs):,} | {pct(r.fc)} | {pct(r.delegated)} | {pct(r.implicit)} | {pct(r.full)} | {pct(r.fc_incl)} |")
    L.append("")
    L.append("Yearly figures are means of weekly shares. Years with fewer sampled weeks are partial.")
    L.append("")
    if ctl["variants"].get("relayers_all_delegated_as_fc", {}).get("would_pass"):
        v = ctl["variants"]["relayers_all_delegated_as_fc"]
        L.append(f"Why it matters for the thesis: the one control rerun that would pass the registered rule counts every relayed meta transaction as function-call activity (out-of-sample gain {pct(v['oos_gain_vs_ar2']['fc_signed_tx'])}, against {pct(v['oos_gain_vs_ar2']['daa'])} for DAA and {pct(v['oos_gain_vs_ar2']['price'])} for price, over {v['weeks']} weeks). This was picked after the fact out of {len(ctl['variants'])} controls, so it is a hypothesis, not a result. It is the claim a next pre-registration should test: delegated signing, not the narrow function-call key, may be where NEAR's app usage now lives.")
        L.append("")

    # 3. Concentration
    top = rec.head(10)
    L.append("## 3. Function-call activity is a handful of apps")
    L.append("")
    L.append(f"Ten contracts carry {pct(top.share_of_fc.sum())} of all sampled function-call transactions. The largest, `{top.fc_receiver.iloc[0]}`, alone carries {pct(top.share_of_fc.iloc[0])}.")
    L.append("")
    L.append("| Contract the key is scoped to | Sampled FC transactions | Weeks seen | Share of FC |")
    L.append("|---|---|---|---|")
    for _, r in top.iterrows():
        L.append(f"| `{r.fc_receiver}` | {int(r.sampled_fc_txs)} | {int(r.weeks_seen)} | {pct(r.share_of_fc)} |")
    L.append("")

    # 4. House of Stake names
    try:
        hos = json.load(open("data/raw/hos.meta.json"))
        L.append("## 4. House of Stake names: keyless, and no delegation yet")
        L.append("")
        L.append(f"House of Stake has leased {hos['names']} top-level names on mainnet ({hos['first_lease']} to {hos['last_lease']}, read from `registry.hos` at {hos['fetched_at'][:16]} UTC). {hos['keyless_names']} of {hos['names']} hold no access key at all: they act only through their holder. {hos['names_with_third_party_extension']} grant a wallet extension to any third party beyond the holder and House of Stake's default `ext.hos`, so delegated signing (the thing this thesis counts) has not reached them yet. A small side series, not part of the registered test. Rebuild: `npx tsx scripts/fetch-hos.ts` (free mainnet reads), rows in `data/raw/hos_names.csv`.")
        L.append("")
    except FileNotFoundError:
        pass

    # The query
    L.append("## The query")
    L.append("")
    L.append("These findings come from the keyless block sample, not from a BigQuery scan (the full key ledger would scan about 20 TB). To reproduce one week from scratch and the yearly table from the committed sample:")
    L.append("")
    L.append("```bash\nmake sample FROM=2025-01-06 TO=2025-01-06\n```")
    L.append("")
    L.append("```python\nimport pandas as pd\nw = pd.read_csv('data/out/weekly.csv')\nw = w[w.txs_classified > 0]\nw['delegated'] = (w.n_delegated_inner_fc + w.n_delegated_inner_full) / w.txs_classified\nprint(w.groupby(w.monday.str[:4])[['fc_only_share', 'delegated']].mean())\n```")
    L.append("")
    L.append("Each transaction's signing key is read with `view_access_key` (now, or on archival RPC at the block before signing) and classified by `scripts/lib/classify.ts`; `sql/02_tx_classified.sql` is the same rule in SQL, tested on fixtures in BigQuery (`data/out/sql_fixture_test.txt`).")
    open("docs/FINDINGS.md", "w").write("\n".join(L) + "\n")
    print("wrote docs/FINDINGS.md")


if __name__ == "__main__":
    main()
