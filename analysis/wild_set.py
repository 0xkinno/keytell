"""The wild set (Part 7 of the plan): the 50 contracts with the most sampled function-call-signed
transactions, with the evidence a person needs to label each one. Writes data/out/wild_set.csv.

Labels are not computed here. data/wild_set_labels.csv holds the labels and who gave them; the labelling
rule is published in docs/WILD_SET.md before any label.
"""
import glob
from collections import Counter

import pandas as pd

FC = {"FUNCTION_CALL", "DELEGATED_INNER_FC"}


def main():
    frames = [pd.read_csv(f, dtype=str, keep_default_na=False) for f in sorted(glob.glob("data/raw/sample/*.txs.csv"))]
    t = pd.concat(frames, ignore_index=True)
    t = t[t.bucket.isin(FC)].copy()
    # The contract a function-call key is scoped to: the outer key's receiver, or the inner key's for meta transactions.
    t["scope"] = t.apply(lambda r: r.fc_receiver if r.bucket == "FUNCTION_CALL" else (r.del_fc_receiver or r.del_receiver), axis=1)
    t["who"] = t.apply(lambda r: r.signer if r.bucket == "FUNCTION_CALL" else (r.del_sender or r.signer), axis=1)
    rows = []
    for scope, g in t.groupby("scope"):
        if not scope:
            continue
        signers = Counter(g.who)
        methods = Counter(m for ms in g.method for m in str(ms).split("|") if m)
        rows.append({
            "scope": scope,
            "sampled_fc_txs": len(g),
            "share_of_fc": round(len(g) / len(t), 5),
            "weeks_seen": g.week.nunique(),
            "first_week": g.week.min(),
            "last_week": g.week.max(),
            "distinct_signers": len(signers),
            "top_signer_share": round(signers.most_common(1)[0][1] / len(g), 4),
            "top_methods": " ".join(f"{m}:{n}" for m, n in methods.most_common(3)),
            "explorer": f"https://nearblocks.io/address/{scope}",
        })
    out = pd.DataFrame(rows).sort_values(["sampled_fc_txs", "scope"], ascending=[False, True]).head(50)
    out.insert(0, "rank", range(1, len(out) + 1))
    # The published rule (docs/WILD_SET.md), applied mechanically. A person gives the final label.
    def propose(r):
        if r.sampled_fc_txs < 5:
            return "unknown (too few sampled transactions)"
        if r.distinct_signers <= 2 or r.top_signer_share >= 0.9:
            return "bot (one operator signs almost all of it)"
        return "app or game (needs a person)"
    out["proposed_label"] = out.apply(propose, axis=1)
    out.to_csv("data/out/wild_set.csv", index=False)
    write_doc(out, len(t))
    print(f"wrote data/out/wild_set.csv: {len(out)} contracts, {out.sampled_fc_txs.sum()} of {len(t)} sampled function-call transactions")


def write_doc(out, total):
    labels = {}
    try:
        lab = pd.read_csv("data/wild_set_labels.csv", dtype=str, keep_default_na=False)
        labels = {r.scope: (r.label, r.labelled_by) for r in lab.itertuples()}
    except FileNotFoundError:
        pass
    L = ["# Wild set", "", "Generated by `analysis/wild_set.py` from the committed sample. The 50 contracts that sampled function-call keys were most often scoped to, with the evidence a person needs to label each one.", ""]
    L += ["## The labelling rule (published before any label)", "",
          "1. **bot**: one operator account signs almost all of the contract's function-call transactions (at most two distinct signers, or the top signer at 90 percent or more). Oracles, batch recorders and account factories land here.",
          "2. **relayer**: the contract creates accounts or relays actions for users who do not sign the outer transaction.",
          "3. **game**: many distinct users, and the methods are game moves (harvest, forge, draw, move, discover).",
          "4. **app**: many distinct users, and the methods are an application's actions (tasks, swaps, orders, posts, logins).",
          "5. **unknown**: fewer than 5 sampled transactions, or the evidence does not settle it.",
          "",
          "Rules 1 and 5 are applied mechanically below as a proposal. Rules 2 to 4 need a person. A label is final only when the `labelled by` column names a person; disagreements between the proposal and the person are kept, not overwritten.", ""]
    n_bot = (out.proposed_label.str.startswith("bot")).sum()
    share_bot = out[out.proposed_label.str.startswith("bot")].sampled_fc_txs.sum() / total
    L += [f"**What it shows already:** {n_bot} of the top 50 are run by one operator, carrying {share_bot * 100:.1f}% of all sampled function-call transactions. Much of what looks like app-held keys is an app's own back office signing for itself.", ""]
    L += ["| Rank | Contract | Sampled FC tx | Weeks | Distinct signers | Top signer | Top methods | Proposed (rule) | Label | Labelled by |", "|---|---|---|---|---|---|---|---|---|---|"]
    for r in out.itertuples():
        lab, by = labels.get(r.scope, ("", "pending"))
        L.append(f"| {r.rank} | [`{r.scope}`]({r.explorer}) | {r.sampled_fc_txs} | {r.weeks_seen} | {r.distinct_signers} | {r.top_signer_share * 100:.0f}% | {str(r.top_methods).replace(':', ' ') if r.top_methods == r.top_methods else ''} | {r.proposed_label} | {lab} | {by} |")
    open("docs/WILD_SET.md", "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
