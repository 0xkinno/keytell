// Writes docs/EVIDENCE.md: every line is a committed command output or a transaction link. Nothing is
// typed by hand: it reads deployments/testnet.json, data/registration.json, data/break.json,
// data/out/bq_runs.jsonl, data/out/results.json, data/out/sql_fixture_test.txt, docs/logs/*.log.
// Usage: npx tsx scripts/evidence.ts [--check]
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const j = (p: string) => (existsSync(p) ? JSON.parse(readFileSync(p, "utf8")) : null);
const t = (p: string) => (existsSync(p) ? readFileSync(p, "utf8") : null);
const tx = (h: string) => `[${h.slice(0, 12)}...](https://testnet.nearblocks.io/txns/${h})`;
const acct = (a: string) => `[\`${a}\`](https://testnet.nearblocks.io/address/${a})`;
const tail = (s: string | null, pat: RegExp, n = 40) => (s ? s.split("\n").filter((l) => pat.test(l)).slice(-n).join("\n") : "not captured");

const dep = j("deployments/testnet.json");
const reg = j("data/registration.json");
if (reg && !reg.registered_at) reg.registered_at = new Date(Number(BigInt(reg.registered_at_ns) / 1_000_000n)).toISOString();
const brk = j("data/break.json");
const res = j("data/out/results.json");
const facts = j("docs/FACTS.json");
const runs = (t("data/out/bq_runs.jsonl") ?? "").trim().split("\n").filter(Boolean).map((l) => JSON.parse(l));
const testLog = t("docs/logs/make-test.log");
const verifyLog = t("e2e/verify.log");

const L: string[] = ["# Evidence", "", "Every line here is a command output or a transaction link, generated by `scripts/evidence.ts` from committed files.", ""];

L.push("## Tests (`make test`)", "");
L.push("Captured in `docs/logs/make-test.log`. The property test runs 10,000 random call sequences under the `proptest` profile; the sandbox tests send every refusal as a real failed transaction to a local NEAR node.", "");
L.push("```", tail(testLog, /test result:|^test .* \.\.\. |PASS|FAIL|^# (tests|pass|fail)|fixtures agree|EXIT/), "```", "");

if (dep) {
  L.push("## Testnet deployment", "");
  L.push(`Built in the pinned image by \`fleet/repro-build.sh\`; wasm sha256 \`${dep.code_hashes.thesis_ledger.wasm_sha256_hex}\` (\`fleet/ours-wasm.sha256\`). Code hash on chain: \`${dep.code_hashes.thesis_ledger.on_chain}\`, equal to the build: ${dep.code_hashes.thesis_ledger.on_chain === dep.code_hashes.thesis_ledger.wasm_sha256_b58 ? "yes" : "no"}.`, "");
  L.push("| Account | Role | Access keys |", "|---|---|---|");
  L.push(`| ${acct(dep.ledger)} | thesis_ledger | ${dep.access_keys.ledger} |`);
  L.push(`| ${acct(dep.crank)} | crank | function-call key \`${dep.crank_post_key.slice(0, 20)}...\` limited to \`${dep.crank_post_key_permission.FunctionCall.method_names.join(", ")}\` on \`${dep.crank_post_key_permission.FunctionCall.receiver_id}\` |`);
  L.push(`| ${acct(dep.publisher)} | publisher | full access (registers claims only) |`, "");
  L.push("| Step | Transaction |", "|---|---|");
  for (const [k, h] of Object.entries(dep.txs)) L.push(`| ${k.replace(/_/g, " ")} | ${tx(h as string)} |`);
  L.push("");
}

if (reg) {
  L.push("## The claim, registered before the out-of-sample data", "");
  L.push(`Claim \`${reg.claim_id ?? reg.claim?.id}\` registered at ${reg.registered_at}: ${tx(reg.tx ?? reg.tx_hash ?? reg.hash)}.`, "");
  L.push("| Query | Window | Bytes billed | Ran at | After registration |", "|---|---|---|---|---|");
  const regMs = Date.parse(reg.registered_at);
  for (const r of runs) L.push(`| \`${r.sql}\` | ${r.start} to ${r.end} | ${Number(r.bytes_billed ?? r.dry_run_bytes).toLocaleString("en-US")} | ${r.ran_at} | ${Date.parse(r.ran_at) > regMs ? "yes" : "no (in-sample)"} |`);
  L.push("");
}

if (brk) {
  L.push("## Break campaign (testnet)", "");
  L.push(`Run at ${brk.ran_at} against a twin ledger ${acct(brk.twin)} with the same code hash as the real one (\`${brk.twin_code_hash}\` = \`${brk.real_code_hash}\`). ${brk.results.filter((r: any) => r.ok_as_designed).length} of ${brk.results.length} attempts behaved as designed.`, "");
  L.push("| Attempt | Signer | Method | Expected | Got | Transaction |", "|---|---|---|---|---|---|");
  for (const r of brk.results) L.push(`| ${r.name} | \`${r.signer}\` | \`${r.method}\` | ${r.expected} | ${r.got} | ${r.hash ? tx(r.hash) : "n/a"} |`);
  L.push("");
}

if (res) {
  L.push("## The backtest (`analysis/method.py`)", "");
  L.push("```", JSON.stringify({ verdict: res.verdict, oos_weeks_scored: res.oos_weeks_scored, best_in_sample_lag: res.best_in_sample_lag, oos_gain_vs_ar2: res.oos_gain_vs_ar2, comparisons: res.comparisons }, null, 2), "```", "");
}

const fx = t("data/out/sql_fixture_test.txt");
if (fx) L.push("## SQL classifier on fixtures in BigQuery (`BQ_TEST=1`)", "", "```", fx.trim(), "```", "");

if (facts?.data) {
  L.push("## Sample against census", "");
  L.push(`${facts.data.weeks_sampled} weeks sampled, ${Number(facts.data.blocks_sampled).toLocaleString("en-US")} blocks, ${Number(facts.data.transactions_classified).toLocaleString("en-US")} transactions classified, ${Number(facts.data.archival_lookups).toLocaleString("en-US")} archival key lookups. ${facts.sentences?.sample_check ?? ""}`, "");
}

const live = j("e2e/live-report.json");
if (live) {
  L.push("## The deployed app, end to end (`e2e/live.mjs`)", "", `Run at ${live.ran_at} against ${live.base}: ${live.passed} of ${live.total} pass.`, "", "| Check | Result | Detail |", "|---|---|---|");
  for (const r of live.results) L.push(`| ${r.name} | ${r.ok ? "PASS" : "FAIL"} | ${String(r.detail).replace(/\|/g, "/")} |`);
  L.push("");
}
const lay = j("e2e/layout-report.json");
if (lay) L.push("## Layout and accessibility (`e2e/layout.mjs`)", "", `Run at ${lay.ran_at} against ${lay.base}: ${lay.clean} of ${lay.total} views clean over ${lay.routes.length} routes and ${lay.viewports.length} viewports (${lay.viewports.join(", ")}).`, "");
if (verifyLog) L.push("## `make verify`", "", "Captured in `e2e/verify.log`.", "", "```", tail(verifyLog, /PASS|FAIL|checks pass/), "```", "");

const text = L.join("\n") + "\n";
if (process.argv.includes("--check")) {
  if ((t("docs/EVIDENCE.md") ?? "") !== text) { console.error("FAIL evidence: docs/EVIDENCE.md is stale"); process.exit(1); }
  console.log("PASS evidence");
} else {
  writeFileSync("docs/EVIDENCE.md", text);
  console.log("wrote docs/EVIDENCE.md");
}
